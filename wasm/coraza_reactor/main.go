// GC tuning. A default GOGC=100 collects roughly every 10 MiB of allocation;
// CRS evaluation allocates about 0.5-1 MiB per 8 KiB body, so an early
// collection lands mid-evaluation and can double that request's latency
// (measured p50 863 ms versus a 333 ms steady-state floor). Raising the heap
// growth target amortises collections across many requests, while
// GOMEMLIMIT keeps the heap target comfortably below the host's 256 MiB
// store limit so the runtime still collects before linear memory traps.
//
// Tradeoff: a larger growth target is faster but retains more heap, and wasm
// linear memory cannot shrink. The 64 MiB soft limit is the measured plateau
// bound: on the reference 6-core host a six-worker pool levels off at about
// 814 MiB RSS (80 MiB linear memory per worker) after warm-up, versus >1.4 GiB
// and still rising with a 192 MiB limit. Keep enough headroom under
// `waf.coraza.memory_limit_bytes` (256 MiB default) for the Go runtime's
// non-heap linear memory.
const (
	gcPercent   = 600
	memoryLimit = 64 << 20
)

func init() {
	debug.SetGCPercent(gcPercent)
	debug.SetMemoryLimit(memoryLimit)
}

// maxInputBytes is the size of the static request buffer exposed to the host.
// Keep this in sync with the host's DEFAULT_MAX_PAYLOAD_BYTES and the input
// buffer size documented in docs/coraza-wasi-reactor.md.
const maxInputBytes = 64 * 1024

// embeddedCRS contains a verbatim, pinned subset of the OWASP Core Rule Set,
// its Apache-2.0 license, provenance and @pmFromFile data files. The bundle is
// generated by scripts/vendor-coraza-crs.sh.
//
//go:embed rules/crs
var embeddedCRS embed.FS

// enginePreamble is the ModSecurity configuration that CRS assumes has already
// been loaded. Response body inspection stays off: the reactor only inspects
// requests and the host does not forward response bodies.
const enginePreamble = `SecRuleEngine On
SecRequestBodyAccess On
SecRequestBodyLimit 131072
SecRequestBodyInMemoryLimit 131072
SecResponseBodyAccess Off
`

// maxRemoveRuleIDs is the hard ABI bound shared with the host
// (crate::waf::prefilter::MAX_REMOVE_RULE_IDS) and the binary wire format.
const maxRemoveRuleIDs = 256

// prefilterArtifact mirrors the fields of rules/crs/prefilter.json that the
// guest needs. Unknown fields are ignored.
type prefilterArtifact struct {
	Rules []struct {
		ID           int  `json:"id"`
		BodyRelevant bool `json:"body_relevant"`
		Gated        bool `json:"gated"`
	} `json:"rules"`
	UngatedRules []struct {
		ID           int  `json:"id"`
		BodyRelevant bool `json:"body_relevant"`
	} `json:"ungated_rules"`
}

// gatedRuleIDs is the only set of rules the guest will remove. It is built
// once at init from the embedded artifact; rules absent from it (ungated,
// unknown, or a chain member with no proof) are never removable, regardless of
// what the payload asks for.
var gatedRuleIDs = map[int]struct{}{}

// loadGatedRuleIDs reads the embedded prefilter artifact. A missing or invalid
// artifact leaves the set empty, which disables removals and evaluates every
// rule: slow but always sound.
func loadGatedRuleIDs() map[int]struct{} {
	ids := make(map[int]struct{})
	data, err := fs.ReadFile(embeddedCRS, "rules/crs/prefilter.json")
	if err != nil {
		return ids
	}
	var artifact prefilterArtifact
	if err := json.Unmarshal(data, &artifact); err != nil {
		return ids
	}
	ungated := make(map[int]struct{})
	for _, rule := range artifact.Rules {
		if !rule.BodyRelevant {
			continue
		}
		if rule.Gated {
			ids[rule.ID] = struct{}{}
		} else {
			ungated[rule.ID] = struct{}{}
		}
	}
	for _, rule := range artifact.UngatedRules {
		if rule.BodyRelevant {
			ungated[rule.ID] = struct{}{}
		}
	}
	for id := range ungated {
		delete(ids, id)
	}
	return ids
}

// removeRules applies the validated subset of ids to this transaction only.
// Coraza's RemoveRuleByID appends to a per-transaction exclusion list, so the
// shared WAF and other in-flight transactions are unaffected.
func removeRules(tx types.Transaction, ids []uint32) {
	for _, id := range filteredRemoveRuleIDs(ids) {
		tx.RemoveRuleByID(id)
	}
}

// filteredRemoveRuleIDs is the pure validation step: duplicates, unknown ids
// and ungated rules are dropped, and the result is bounded by
// maxRemoveRuleIDs. A forged payload cannot disable a rule outside the gated
// set.
func filteredRemoveRuleIDs(ids []uint32) []int {
	if len(ids) == 0 || len(gatedRuleIDs) == 0 {
		return nil
	}
	out := make([]int, 0, len(ids))
	seen := make(map[uint32]struct{}, len(ids))
	for _, id := range ids {
		if len(out) >= maxRemoveRuleIDs {
			break
		}
		if _, ok := seen[id]; ok {
			continue
		}
		seen[id] = struct{}{}
		if _, ok := gatedRuleIDs[int(id)]; !ok {
			continue
		}
		out = append(out, int(id))
	}
	return out
}

// inputBuf is static storage whose address is advertised through input_base.
// It must never move (Go's GC is non-moving for this kind of global), so the
// host may keep using the returned offset for the lifetime of the instance.
var inputBuf [maxInputBytes]byte

// decisionBuf is the fixed decision header. Byte 0..3 hold the decision code
// (0 allow, 1 block, negative guest error); bytes 4..7 hold the HTTP status
// for a block. The host reads this after `eval` returns so it can recover the
// extended decision without another copy or JSON decode.
var decisionBuf [8]byte

//go:wasmexport decision_base
func wafDecisionBase() int32 {
	return int32(uintptr(unsafe.Pointer(&decisionBuf[0])))
}

