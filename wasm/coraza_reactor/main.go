// Request is the JSON payload shape produced by src/waf/wasm_reactor.rs.
// Headers are accepted both as [[name, value], ...] (the host's current
// form) and as {"name": "value"} for manual testing.
//
// BodyEncoding distinguishes text bodies from binary ones. The host sends
// "utf8" (or omits the field, which is treated as "utf8") when the raw body is
// valid UTF-8 and "base64" otherwise, so invalid UTF-8 bytes survive
// inspection instead of being replaced with U+FFFD. BodySize is a pointer so
// payloads that omit it stay compatible; when present it must equal the
// decoded body length.
//
// RemoveRuleIDs is the host-side gate: gated CRS rules whose required literals
// are provably absent from the request. The guest validates every id against
// its own copy of the prefilter artifact, so a forged payload cannot disable an
// ungated or unknown rule.
type Request struct {
	Method        string          `json:"method"`
	URI           string          `json:"uri"`
	HTTPVersion   string          `json:"http_version"`
	Headers       json.RawMessage `json:"headers"`
	Body          *string         `json:"body"`
	BodySize      *int            `json:"body_size"`
	BodyEncoding  string          `json:"body_encoding"`
	RemoveRuleIDs []uint32        `json:"remove_rule_ids"`
}

// Guest error codes. The host maps -5 to a body-encoding error.
const (
	errPayload      = -2
	errBounds       = -3
	errBody         = -4
	errBodyEncoding = -5
)

const (
	bodyEncodingUTF8   = "utf8"
	bodyEncodingBase64 = "base64"
)

// decodeBody resolves the request body according to its encoding and validates
// the declared raw length. An empty encoding means "utf8" for backwards
// compatibility with payloads built before body encodings existed.
func decodeBody(req *Request) ([]byte, int) {
	if req.Body == nil {
		return nil, 0
	}
	encoding := req.BodyEncoding
	if encoding == "" {
		encoding = bodyEncodingUTF8
	}

	var body []byte
	switch encoding {
	case bodyEncodingUTF8:
		body = []byte(*req.Body)
	case bodyEncodingBase64:
		decoded, err := base64.StdEncoding.DecodeString(*req.Body)
		if err != nil {
			return nil, errBodyEncoding
		}
		body = decoded
	default:
		return nil, errBodyEncoding
	}

	if req.BodySize != nil && *req.BodySize >= 0 && *req.BodySize != len(body) {
		return nil, errBodyEncoding
	}
	return body, 0
}

func decodeHeaders(raw json.RawMessage) [][2]string {
	if len(raw) == 0 || string(raw) == "null" {
		return nil
	}
	var pairs [][2]string
	if err := json.Unmarshal(raw, &pairs); err == nil {
		return pairs
	}
	var object map[string]string
	if err := json.Unmarshal(raw, &object); err == nil {
		out := make([][2]string, 0, len(object))
		for k, v := range object {
			out = append(out, [2]string{k, v})
		}
		return out
	}
	return nil
}

// binaryMagic marks the compact binary request envelope. It must match
// crate::waf::coraza_payload::BINARY_MAGIC on the host.
const binaryMagic = 0xCAFEBABE

// binaryHeaderBytes is the fixed prefix of the binary envelope.
const binaryHeaderBytes = 32

// parsedRequest is the backend-neutral request shape used by the evaluator.
type parsedRequest struct {
	method        string
	uri           string
	httpVersion   string
	headers       [][2]string
	body          []byte
	hasBody       bool
	bodyErr       int32
	removeRuleIDs []uint32
}

// bytesToString aliases a byte slice as a string without copying. The payload
// lives in the static input buffer for the duration of the evaluation, so the
// alias is valid while the transaction runs.
func bytesToString(b []byte) string {
	if len(b) == 0 {
		return ""
	}
	return unsafe.String(&b[0], len(b))
}

// parseBinaryRequest decodes the compact binary envelope written by the host.
// It returns nil when the payload is not a binary envelope (for example the
// legacy JSON payload), so the caller can fall back to JSON.
func parseBinaryRequest(payload []byte) (*parsedRequest, int) {
	if len(payload) < binaryHeaderBytes {
		return nil, 0
	}
	if binary.LittleEndian.Uint32(payload[0:4]) != binaryMagic {
		return nil, 0
	}
	if binary.LittleEndian.Uint16(payload[4:6]) != 1 {
		return nil, errPayload
	}
	methodLen := int(binary.LittleEndian.Uint32(payload[8:12]))
	uriLen := int(binary.LittleEndian.Uint32(payload[12:16]))
	versionLen := int(binary.LittleEndian.Uint32(payload[16:20]))
	bodyLen := int(binary.LittleEndian.Uint32(payload[20:24]))
	headerCount := int(binary.LittleEndian.Uint32(payload[24:28]))
	removeCount := int(binary.LittleEndian.Uint32(payload[28:32]))
	if removeCount > maxRemoveRuleIDs {
		return nil, errPayload
	}

	off := binaryHeaderBytes
	need := func(n int) bool { return n >= 0 && off+n <= len(payload) }
	if !need(methodLen + uriLen + versionLen + bodyLen) {
		return nil, errBounds
	}
	req := &parsedRequest{}
	req.method = bytesToString(payload[off : off+methodLen])
	off += methodLen
	req.uri = bytesToString(payload[off : off+uriLen])
	off += uriLen
	req.httpVersion = bytesToString(payload[off : off+versionLen])
	off += versionLen
	if bodyLen > 0 {
		req.body = payload[off : off+bodyLen]
		req.hasBody = true
	}
	off += bodyLen

	req.headers = make([][2]string, 0, headerCount)
	for i := 0; i < headerCount; i++ {
		if !need(4) {
			return nil, errBounds
		}
		nameLen := int(binary.LittleEndian.Uint32(payload[off : off+4]))
		off += 4
		if !need(nameLen) {
			return nil, errBounds
		}
		name := bytesToString(payload[off : off+nameLen])
		off += nameLen
		if !need(4) {
			return nil, errBounds
		}
		valueLen := int(binary.LittleEndian.Uint32(payload[off : off+4]))
		off += 4
		if !need(valueLen) {
			return nil, errBounds
		}
		value := bytesToString(payload[off : off+valueLen])
		off += valueLen
		req.headers = append(req.headers, [2]string{name, value})
	}

	req.removeRuleIDs = make([]uint32, 0, removeCount)
	for i := 0; i < removeCount; i++ {
		if !need(4) {
			return nil, errBounds
		}
		req.removeRuleIDs = append(req.removeRuleIDs, binary.LittleEndian.Uint32(payload[off:off+4]))
		off += 4
	}
	return req, 0
}

func ensureEngine() {
	if engine != nil || initErr != nil {
		return
	}
	crsRules, err := fs.ReadFile(embeddedCRS, "rules/crs/crs.conf")
	if err != nil {
		initErr = err
		return
	}
	crsData, err := fs.Sub(embeddedCRS, "rules/crs/rules")
	if err != nil {
		initErr = err
		return
	}
	directives := enginePreamble + string(crsRules)
	engine, initErr = coraza.NewWAF(
		coraza.NewWAFConfig().
			WithRootFS(crsData).
			WithDirectives(strings.TrimSpace(directives)),
	)
	if initErr == nil {
		gatedRuleIDs = loadGatedRuleIDs()
	}
}

//go:wasmexport input_base
func inputBase() int32 {
	return int32(uintptr(unsafe.Pointer(&inputBuf[0])))
}

//go:wasmexport init
func wafInit() int32 {
	ensureEngine()
	if initErr != nil {
		return 1
	}
	return 0
}

//go:wasmexport eval
func wafEval(ptr int32, length int32) (code int32) {
	defer func() {
		binary.LittleEndian.PutUint32(decisionBuf[0:4], uint32(code))
		if code == 1 {
			binary.LittleEndian.PutUint32(decisionBuf[4:8], 403)
		} else {
			binary.LittleEndian.PutUint32(decisionBuf[4:8], 0)
		}
	}()
	if engine == nil {
		ensureEngine()
		if initErr != nil {
			return -1
		}
	}
	if length < 0 || int(length) > maxInputBytes {
		return errBounds
	}
	if ptr < 0 {
		return errPayload
	}

	base := uintptr(unsafe.Pointer(&inputBuf[0]))
	p := uintptr(uint32(ptr))
	if p < base || p+uintptr(length) > base+uintptr(maxInputBytes) {
		return errBounds
	}

	payload := unsafe.Slice((*byte)(unsafe.Pointer(p)), int(length))

	// Fast path: the compact binary envelope. The host writes it directly into
	// the static input buffer, so the guest only slices it and never decodes
	// JSON or base64. A non-matching magic falls back to the legacy JSON path.
	if req, code := parseBinaryRequest(payload); req != nil {
		if code != 0 {
			return int32(code)
		}
		return evalParsed(req)
	}

	var req Request
	if err := json.Unmarshal(payload, &req); err != nil {
		return errPayload
	}
	if len(req.RemoveRuleIDs) > maxRemoveRuleIDs {
		return errPayload
	}

	parsed := &parsedRequest{
		method:        req.Method,
		uri:           req.URI,
		httpVersion:   req.HTTPVersion,
		headers:       decodeHeaders(req.Headers),
		removeRuleIDs: req.RemoveRuleIDs,
	}
	if req.Body != nil && *req.Body != "" {
		body, code := decodeBody(&req)
		if code != 0 {
			parsed.bodyErr = int32(code)
		} else {
			parsed.body = body
			parsed.hasBody = true
		}
	}
	return evalParsed(parsed)
}

// evalParsed runs one transaction from the backend-neutral request shape.
func evalParsed(req *parsedRequest) int32 {
	tx := engine.NewTransaction()
	defer tx.Close()

	// Remove only the host-proven gated rules before the first phase so they
	// never evaluate. Ungated and unknown ids are ignored by removeRules.
	removeRules(tx, req.removeRuleIDs)

	version := req.httpVersion
	if version == "" {
		version = "HTTP/1.1"
	}
	uri := req.uri
	if uri == "" {
		uri = "/"
	}
	method := req.method
	if method == "" {
		method = "GET"
	}

	tx.ProcessURI(uri, method, version)
	for _, h := range req.headers {
		tx.AddRequestHeader(h[0], h[1])
	}

	if it := tx.ProcessRequestHeaders(); it != nil {
		return 1
	}

	// A malformed body is only reported after phase-1 rules had a chance to
	// deny the request, preserving the historical fail-closed ordering.
	if req.bodyErr != 0 {
		return req.bodyErr
	}

	if req.hasBody && len(req.body) > 0 {
		if _, _, err := tx.WriteRequestBody(req.body); err != nil {
			return errBody
		}
	}
	if it, err := tx.ProcessRequestBody(); err != nil {
		return errBody
	} else if it != nil {
		return 1
	}

	if tx.IsInterrupted() {
		return 1
	}
	return 0
}

