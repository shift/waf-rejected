//go:build wasip1 && wasm

// Package main implements a Coraza-based WASI reactor for the WAF-Rejected
// host ABI. It is intentionally a reactor (c-shared) rather than the
// historical GOOS=js command module: there is no JavaScript bridge and no
// dependency on files under rules/ at runtime.
package main

import (
	"embed"
	"encoding/base64"
	"encoding/json"
	"io/fs"
	"runtime/debug"
	"strings"
	"unsafe"

	"github.com/corazawaf/coraza/v3"
)

// GC tuning. A default GOGC=100 collects roughly every 10 MiB of allocation;
// CRS evaluation allocates about 0.5-1 MiB per 8 KiB body, so an early
// collection lands mid-evaluation and can double that request's latency
// (measured p50 863 ms versus a 333 ms steady-state floor). Raising the heap
// growth target amortises collections across many requests, while
// GOMEMLIMIT keeps the heap target comfortably below the host's 256 MiB
// store limit so the runtime still collects before linear memory traps.
//
// Tradeoff: resident memory is higher and a collection, when it does happen,
// scans a larger live heap. The 192 MiB soft limit leaves 64 MiB of headroom
// for non-heap/wasm overhead under the 256 MiB store cap.
const (
	gcPercent   = 600
	memoryLimit = 192 << 20
)

func init() {
	debug.SetGCPercent(gcPercent)
	debug.SetMemoryLimit(memoryLimit)
}

// maxInputBytes is the size of the static request buffer exposed to the host.
// Keep this in sync with the host's DEFAULT_MAX_PAYLOAD_BYTES and the input
// buffer size documented in docs/coraza-wasi-reactor.md.
const maxInputBytes = 64 * 1024

// embeddedCRS contains a verbatim, pinned subset of the OWASP Core Rule Set,
// its Apache-2.0 license, provenance and @pmFromFile data files. The bundle is
// generated by scripts/vendor-coraza-crs.sh.
//
//go:embed rules/crs
var embeddedCRS embed.FS

// enginePreamble is the ModSecurity configuration that CRS assumes has already
// been loaded. Response body inspection stays off: the reactor only inspects
// requests and the host does not forward response bodies.
const enginePreamble = `SecRuleEngine On
SecRequestBodyAccess On
SecRequestBodyLimit 131072
SecRequestBodyInMemoryLimit 131072
SecResponseBodyAccess Off
`

// inputBuf is static storage whose address is advertised through input_base.
// It must never move (Go's GC is non-moving for this kind of global), so the
// host may keep using the returned offset for the lifetime of the instance.
var inputBuf [maxInputBytes]byte

var (
	engine  coraza.WAF
	initErr error
)

// Request is the JSON payload shape produced by src/waf/wasm_reactor.rs.
// Headers are accepted both as [[name, value], ...] (the host's current
// form) and as {"name": "value"} for manual testing.
//
// BodyEncoding distinguishes text bodies from binary ones. The host sends
// "utf8" (or omits the field, which is treated as "utf8") when the raw body is
// valid UTF-8 and "base64" otherwise, so invalid UTF-8 bytes survive
// inspection instead of being replaced with U+FFFD. BodySize is a pointer so
// payloads that omit it stay compatible; when present it must equal the
// decoded body length.
type Request struct {
	Method       string          `json:"method"`
	URI          string          `json:"uri"`
	HTTPVersion  string          `json:"http_version"`
	Headers      json.RawMessage `json:"headers"`
	Body         *string         `json:"body"`
	BodySize     *int            `json:"body_size"`
	BodyEncoding string          `json:"body_encoding"`
}

// Guest error codes. The host maps -5 to a body-encoding error.
const (
	errPayload      = -2
	errBounds       = -3
	errBody         = -4
	errBodyEncoding = -5
)

const (
	bodyEncodingUTF8   = "utf8"
	bodyEncodingBase64 = "base64"
)

// decodeBody resolves the request body according to its encoding and validates
// the declared raw length. An empty encoding means "utf8" for backwards
// compatibility with payloads built before body encodings existed.
func decodeBody(req *Request) ([]byte, int) {
	if req.Body == nil {
		return nil, 0
	}
	encoding := req.BodyEncoding
	if encoding == "" {
		encoding = bodyEncodingUTF8
	}

	var body []byte
	switch encoding {
	case bodyEncodingUTF8:
		body = []byte(*req.Body)
	case bodyEncodingBase64:
		decoded, err := base64.StdEncoding.DecodeString(*req.Body)
		if err != nil {
			return nil, errBodyEncoding
		}
		body = decoded
	default:
		return nil, errBodyEncoding
	}

	if req.BodySize != nil && *req.BodySize >= 0 && *req.BodySize != len(body) {
		return nil, errBodyEncoding
	}
	return body, 0
}

func decodeHeaders(raw json.RawMessage) [][2]string {
	if len(raw) == 0 || string(raw) == "null" {
		return nil
	}
	var pairs [][2]string
	if err := json.Unmarshal(raw, &pairs); err == nil {
		return pairs
	}
	var object map[string]string
	if err := json.Unmarshal(raw, &object); err == nil {
		out := make([][2]string, 0, len(object))
		for k, v := range object {
			out = append(out, [2]string{k, v})
		}
		return out
	}
	return nil
}

func ensureEngine() {
	if engine != nil || initErr != nil {
		return
	}
	crsRules, err := fs.ReadFile(embeddedCRS, "rules/crs/crs.conf")
	if err != nil {
		initErr = err
		return
	}
	crsData, err := fs.Sub(embeddedCRS, "rules/crs/rules")
	if err != nil {
		initErr = err
		return
	}
	directives := enginePreamble + string(crsRules)
	engine, initErr = coraza.NewWAF(
		coraza.NewWAFConfig().
			WithRootFS(crsData).
			WithDirectives(strings.TrimSpace(directives)),
	)
}

//go:wasmexport input_base
func inputBase() int32 {
	return int32(uintptr(unsafe.Pointer(&inputBuf[0])))
}

//go:wasmexport init
func wafInit() int32 {
	ensureEngine()
	if initErr != nil {
		return 1
	}
	return 0
}

//go:wasmexport eval
func wafEval(ptr int32, length int32) int32 {
	if engine == nil {
		ensureEngine()
		if initErr != nil {
			return -1
		}
	}
	if length < 0 || int(length) > maxInputBytes {
		return errBounds
	}
	if ptr < 0 {
		return errPayload
	}

	base := uintptr(unsafe.Pointer(&inputBuf[0]))
	p := uintptr(uint32(ptr))
	if p < base || p+uintptr(length) > base+uintptr(maxInputBytes) {
		return errBounds
	}

	payload := unsafe.Slice((*byte)(unsafe.Pointer(p)), int(length))
	var req Request
	if err := json.Unmarshal(payload, &req); err != nil {
		return errPayload
	}

	tx := engine.NewTransaction()
	defer tx.Close()

	version := req.HTTPVersion
	if version == "" {
		version = "HTTP/1.1"
	}
	uri := req.URI
	if uri == "" {
		uri = "/"
	}
	method := req.Method
	if method == "" {
		method = "GET"
	}

	tx.ProcessURI(uri, method, version)
	for _, h := range decodeHeaders(req.Headers) {
		tx.AddRequestHeader(h[0], h[1])
	}

	if it := tx.ProcessRequestHeaders(); it != nil {
		return 1
	}

	if req.Body != nil && *req.Body != "" {
		body, code := decodeBody(&req)
		if code != 0 {
			return int32(code)
		}
		if _, _, err := tx.WriteRequestBody(body); err != nil {
			return errBody
		}
	}
	if it, err := tx.ProcessRequestBody(); err != nil {
		return errBody
	} else if it != nil {
		return 1
	}

	if tx.IsInterrupted() {
		return 1
	}
	return 0
}

//go:wasmexport free
func wafFree(ptr int32, length int32) {
	// The input buffer is static and owned by the module, so there is nothing
	// to reclaim. Kept in the ABI for host symmetry and future allocators.
}

func main() {}
