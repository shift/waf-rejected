#!/usr/bin/env bash
# Vendor the request-side OWASP Core Rule Set into the Coraza reactor.
#
# Usage: ./scripts/vendor-coraza-crs.sh
#
# Downloads a pinned CRS release from the official repository, copies the
# request-side rule files and their data dependencies, and flattens the
# setup + rule files into a single directive bundle for go:embed.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$ROOT/wasm/coraza_reactor/rules/crs"
CRS_VERSION="4.14.0"
CRS_COMMIT="b5b788b5bc50e68836e17995b191f72e848fed75"
TARBALL="https://codeload.github.com/coreruleset/coreruleset/tar.gz/refs/tags/v${CRS_VERSION}"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

curl -sSL --fail --max-time 120 "$TARBALL" -o "$WORK/crs.tar.gz"
tar xzf "$WORK/crs.tar.gz" -C "$WORK" --strip-components=1
SRC="$WORK"

# The reactor inspects gRPC envelopes before Coraza sees the request, but CRS
# rule 920420 still rejects `application/grpc*` unless the media types are in
# the allowed content-type policy. Add them here so a regenerated bundle does
# not block every gRPC call. Only the default initialisation rule is patched;
# the operator-facing crs-setup.conf.example stays upstream-clean.
perl -0pi -e "s#setvar:'tx\\.allowed_request_content_type=\\|application/x-www-form-urlencoded\\| \\|multipart/form-data\\| \\|text/xml\\| \\|application/xml\\| \\|application/soap\\+xml\\| \\|application/json\\|'#setvar:'tx.allowed_request_content_type=|application/x-www-form-urlencoded| |multipart/form-data| |text/xml| |application/xml| |application/soap+xml| |application/json| |application/grpc| |application/grpc+proto| |application/grpc+json| |application/grpc-web| |application/grpc-web+proto| |application/grpc-web-text|'#g" \
  "$SRC/rules/REQUEST-901-INITIALIZATION.conf"

rm -rf "$DEST"
mkdir -p "$DEST/rules"

cp "$SRC/LICENSE" "$DEST/LICENSE"
cp "$SRC/crs-setup.conf.example" "$DEST/crs-setup.conf"

# Full request-side CRS rule set (phases 1 and 2). Response rules are not
# included because the reactor has SecResponseBodyAccess Off.
RULES=(
  901-INITIALIZATION
  905-COMMON-EXCEPTIONS
  911-METHOD-ENFORCEMENT
  913-SCANNER-DETECTION
  920-PROTOCOL-ENFORCEMENT
  921-PROTOCOL-ATTACK
  922-MULTIPART-ATTACK
  930-APPLICATION-ATTACK-LFI
  931-APPLICATION-ATTACK-RFI
  932-APPLICATION-ATTACK-RCE
  933-APPLICATION-ATTACK-PHP
  934-APPLICATION-ATTACK-GENERIC
  941-APPLICATION-ATTACK-XSS
  942-APPLICATION-ATTACK-SQLI
  943-APPLICATION-ATTACK-SESSION-FIXATION
  944-APPLICATION-ATTACK-JAVA
  949-BLOCKING-EVALUATION
)

BUNDLE="$DEST/crs.conf"
: > "$BUNDLE"
{
  echo "# Generated by scripts/vendor-coraza-crs.sh -- do not edit."
  echo "# OWASP CRS v${CRS_VERSION}, commit ${CRS_COMMIT}."
  echo
} >> "$BUNDLE"

cp "$SRC/crs-setup.conf.example" "$DEST/rules/crs-setup.conf"
cat "$SRC/crs-setup.conf.example" >> "$BUNDLE"
echo >> "$BUNDLE"

for name in "${RULES[@]}"; do
  file="REQUEST-${name}.conf"
  cp "$SRC/rules/$file" "$DEST/rules/$file"
  {
    echo "# ---- ${file} ----"
    cat "$SRC/rules/$file"
    echo
  } >> "$BUNDLE"
done

# @pmFromFile data dependencies used by the selected request rules.
cp "$SRC"/rules/*.data "$DEST/rules/"

cat > "$DEST/PROVENANCE.md" <<EOF
# OWASP Core Rule Set provenance

- Project: OWASP Core Rule Set (CRS)
- Version: ${CRS_VERSION}
- Commit: \`${CRS_COMMIT}\` (tag \`v${CRS_VERSION}\`)
- Source: ${TARBALL}
- License: Apache License 2.0, see \`LICENSE\` in this directory.

## Vendored content

\`crs-setup.conf\` is the upstream \`crs-setup.conf.example\` unmodified.
\`crs.conf\` is a generated flattening of the setup file followed by the
request-side rule files below. The individual files are kept alongside it for
auditability.

Included rule files:

$(for name in "${RULES[@]}"; do echo "- \`REQUEST-${name}.conf\`"; done)

Included data files: all upstream \`rules/*.data\` files used by the selected
rules through \`@pmFromFile\`.

## Not included

- Response inspection rules (\`RESPONSE-950\` through \`RESPONSE-980\`); the
  reactor sets \`SecResponseBodyAccess Off\`.
- Example customisation files (\`REQUEST-900-...\`, \`REQUEST-999-...\`); these
  are deployment-specific and contain no upstream detection rules.
- CRS plugins and the regression test corpus.

## Transforming directives

The bundle is concatenated verbatim. \`@pmFromFile\` keeps its upstream filename
and resolves through Coraza's \`WithRootFS\`, which is an embedded copy of
\`rules/\`; no runtime filesystem access is required.
EOF

echo "vendored CRS ${CRS_VERSION} (${CRS_COMMIT}) into ${DEST}"
